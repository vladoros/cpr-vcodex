inline const char* const* petFrame(const int species, const Mood mood) {
  const int s = species >= 0 && species < kPetSpeciesCount ? species : 0;
  const int m = static_cast<int>(mood);
  return kPetFrames[s][m >= 0 && m < kPetMoods ? m : 0];
}

